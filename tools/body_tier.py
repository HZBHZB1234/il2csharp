"""Measure the BODY tier: stub the missing names until the declaration tier is
empty, then count what is left.

A declaration error makes Roslyn skip method-body binding entirely (see
docs/todo.md), so every compile count this project quoted is a declaration
count. This driver copies the tree once, then iterates:

    compile -> collect CS0234/CS0246 names -> append `internal class <Name> {}`
    stubs (in their namespace, when the message names one) -> compile again

until the declaration tier stops shrinking or the iteration cap is reached. The
remaining errors ARE the body tier.

Usage:
    python tools/body_tier.py <fixture> <label> <report.json> [max_rounds]
"""
import glob
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
from collections import Counter

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(REPO, 'tools'))
import compile_gate as cg  # noqa: E402

BCL_SKIP = ('mscorlib', 'System.', 'System', 'Mono.', 'netstandard')
DECL_CODES = ('CS0234', 'CS0246', 'CS0116')
NAMES_RX = [
    ('CS0246', re.compile(r"error CS0246: .*?'([A-Za-z_][\w.<>`]*)'")),
    ('CS0234', re.compile(r"error CS0234: .*?'([A-Za-z_][\w.]*)'")),
]


def collect_sources(tree):
    out = []
    for name in sorted(os.listdir(tree)):
        d = os.path.join(tree, name)
        if not os.path.isdir(d):
            continue
        if any(name == p or name.startswith(p) for p in BCL_SKIP):
            continue
        out.extend(sorted(glob.glob(os.path.join(d, '**', '*.cs'),
                                   recursive=True)))
    return out


def compile_once(scratch, files, refs, tag):
    rsp = os.path.join(scratch, 'rsp_%s.txt' % tag)
    cmd = ['-nologo', '-target:library', '-unsafe', '-nowarn:1701,1702',
           '-utf8output', '-out:' + os.path.join(scratch, 'out_%s.dll' % tag)]
    cmd += ['-r:"%s"' % r for r in refs]
    cmd += ['"%s"' % f for f in files]
    with open(rsp, 'w', encoding='utf-8') as fh:
        fh.write('\n'.join(cmd) + '\n')
    proc = subprocess.run([shutil.which('dotnet') or 'dotnet', cg.find_csc(),
                           '-noconfig', '@' + rsp], capture_output=True)
    out = cg._decode(proc.stdout) + cg._decode(proc.stderr)
    rows = [l for l in out.splitlines() if ' error ' in l]
    return rows


def main(argv):
    fixture, label, report = argv[1], argv[2], os.path.abspath(argv[3])
    rounds = int(argv[4]) if len(argv) > 4 else 6
    tree = os.path.join(REPO, 'out', fixture, label)
    scratch = tempfile.mkdtemp(prefix='il2csharp_bodytier_')
    files = collect_sources(tree)
    mdir = glob.glob(os.path.join(REPO, 'fixtures', fixture, 'build',
                                  '*BackUpThisFolder*', 'Managed'))[0]
    refs = [os.path.join(mdir, f) for f in sorted(os.listdir(mdir))
            if f.endswith('.dll')]
    stub_path = os.path.join(scratch, '__MissingStubs.cs')
    stubs = ['// generated by tools/body_tier.py -- diagnostic only']
    open(stub_path, 'w', encoding='utf-8', newline='\n').write('\n'.join(stubs))
    files = files + [stub_path]
    history = []
    for r in range(rounds):
        rows = compile_once(scratch, files, refs, r)
        codes = Counter(re.findall(r'error (CS\d+)', '\n'.join(rows)))
        decl = sum(v for k, v in codes.items() if k in DECL_CODES)
        print('round %d: errors %d (declaration %d) top %s'
              % (r, len(rows), decl, codes.most_common(5)))
        history.append({'round': r, 'errors': len(rows),
                        'declaration': decl,
                        'codes': dict(codes.most_common(12))})
        if decl == 0:
            break
        seen = set()
        for row in rows:
            for code, rx in NAMES_RX:
                if code not in row:
                    continue
                m = rx.search(row)
                if not m:
                    continue
                name = m.group(1).split('<')[0].strip('.')
                if not name or name in seen:
                    continue
                seen.add(name)
                ns, _, short = name.rpartition('.')
                if ns:
                    stubs.append('namespace %s { internal class %s { } }'
                                 % (ns, short))
                else:
                    stubs.append('internal class %s { }' % short)
        open(stub_path, 'w', encoding='utf-8', newline='\n').write(
            '\n'.join(stubs))
        print('   added %d stubs' % len(seen))
        if not seen:
            break
    out = {'fixture': fixture, 'label': label, 'sources': len(files) - 1,
           'rounds': history}
    with open(report, 'w', encoding='utf-8') as fh:
        json.dump(out, fh, indent=1)
    print('body tier (last round errors):',
          history[-1]['errors'] if history else 0)
    print('report ->', report)
    return 0


if __name__ == '__main__':
    raise SystemExit(main(sys.argv))
