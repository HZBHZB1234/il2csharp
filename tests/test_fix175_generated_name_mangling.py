"""fix 175: a generated name whose brackets carry a type argument list.

The file writer mangles IL-only characters out of compiler-generated
identifiers (`<>c`, `<Foo>d__13`, `<>9__0_0`) so C# can accept them. The
pattern matched a bracket run whose inside is word characters and dots, and
a separate `<>` form -- which between them cover every generated name in the
game's own assemblies.

`System.Core`/`System.Linq.Parallel.QueryResults` carries one more:
`<System_Collections_Generic_IEnumerable<T>_GetEnumerator>d__21`, an
iterator state machine named after the interface it implements. Its own
brackets contain a type argument list, so neither form could span it and the
raw `<`/`>` reached the file: the only parse error (4 ERROR nodes, 1 file)
on a 36,331-file declaration build of all 161 images.

The extension must not fire on legal source, which is what these tests pin:
`List<Foo<int>>`, `Dictionary<string, List<int>>`, comparison chains, and
rich-text literals like `<color=yellow>`.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from il2cpp.text import MANGLED_IDENT_RX


def mangle(text):
    return MANGLED_IDENT_RX.sub(
        lambda m: m.group(0).replace('<', '_').replace('>', '_')
        .replace('.', '_').replace('|', '_'), text)


GENERATED = '<System_Collections_Generic_IEnumerable<T>_GetEnumerator>d__21'
MANGLED = '_System_Collections_Generic_IEnumerable_T__GetEnumerator_d__21'


def test_a_generated_name_with_a_type_argument_list_is_mangled():
    assert mangle(GENERATED) == MANGLED


def test_both_spellings_of_that_name_move_together():
    src = 'partial class %s {\n    public %s(int s) { }\n}' % (GENERATED, GENERATED)
    out = mangle(src)
    assert out.count(MANGLED) == 2
    assert '<' not in out and '>' not in out


def test_the_plain_generated_names_still_mangle():
    assert mangle('<>c') == '__c'
    assert mangle('<Foo>d__13') == '_Foo_d__13'
    assert mangle('<>9__11_0') == '__9__11_0'
    assert mangle('<PrivateImplementationDetails>') \
        == '_PrivateImplementationDetails_'


LEGAL = [
    'Dictionary<string, List<int>> d = new Dictionary<string, List<int>>();',
    'List<Foo<int>> x = default;',
    'public partial interface IFoo<out T> : IBar<T> { }',
    'class Box<T> where T : class { }',
    'if (a < b && c > d) { }',
    'var v = new KeyValuePair<string, int>("a", 1);',
    'Func<int, Func<string, bool>> f = null;',
    'private void M<T>(T value) { }',
    'System.Collections.Generic.IEnumerator<T> GetEnumerator()',
]


def test_legal_generic_source_is_untouched():
    for line in LEGAL:
        assert mangle(line) == line, line


RICH_TEXT = [
    'text2 = "<color=yellow>Hello</color>";',
    'log = "<auto-generated>";',
    'hint = "<#FFFF80>";',
]


def test_rich_text_literals_are_untouched():
    """The mangler runs on raw file text, before any literal masking, so it
    must not see a tag as a generated name."""
    for line in RICH_TEXT:
        assert mangle(line) == line, line
