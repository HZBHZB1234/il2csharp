"""tools/compile_corpus.py: merge a tree's shared-stub files into one class.

`__SharedBodyStubs.cs` members are real methods with bodies
(`internal static object sub_<va>(params object[] args) { throw ...; }`), one
file per image, and two images can reference the same native address. The
whole-tree compile used to collect *signature lines* and drop the bodies,
which produced an unparseable temporary file -- 91 CS1002 in a compile whose
job was to measure recovered bodies. This pins the member-block extraction and
the per-address dedupe.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(
    os.path.abspath(__file__))), "tools"))

from compile_corpus import _stub_members  # noqa: E402

STUB = """// <auto-generated>
internal static class __SharedBodyStubs
{
    // 0x180002a80: unregistered native target
    internal static object sub_180002a80(params object[] args)
    {
        throw new System.NotImplementedException("unresolved shared native body 0x180002a80");
    }
    // 0x1800037e0: shared body, 3 owners
    internal static object sub_1800037e0(params object[] args)
    {
        throw new System.NotImplementedException("unresolved shared native body 0x1800037e0");
    }
}
"""

OTHER = """internal static class __SharedBodyStubs
{
    internal static object sub_180002a80(params object[] args)
    {
        throw new System.NotImplementedException("unresolved shared native body 0x180002a80");
    }
    internal static object sub_180009000(params object[] args)
    {
        throw new System.NotImplementedException("another address");
    }
}
"""


def test_members_are_extracted_with_their_bodies():
    members = _stub_members(STUB)
    assert [va for va, _ in members] == ['sub_180002a80', 'sub_1800037e0']
    for _va, block in members:
        text = "\n".join(block)
        assert text.count('{') == text.count('}')
        assert 'throw new System.NotImplementedException' in text
        assert text.strip().endswith('}')


def test_comments_before_a_member_are_not_part_of_it():
    _va, block = _stub_members(STUB)[0]
    assert block[0].strip().startswith('internal static object sub_')
    assert not any('native target' in line for line in block)


def test_duplicate_addresses_across_images_collapse():
    seen = {}
    merged = []
    for text in (STUB, OTHER):
        for va, block in _stub_members(text):
            if va in seen:
                continue
            seen[va] = True
            merged.extend(block)
    body = "\n".join(merged)
    assert body.count('sub_180002a80(params object[] args)') == 1
    assert body.count('sub_1800037e0(') == 1
    assert body.count('sub_180009000(') == 1
    assert body.count('{') == body.count('}')
